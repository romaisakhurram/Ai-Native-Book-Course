#!/usr/bin/env node
/**
 * Frontend Environment Setup Script
 * Sets up global backend URL configuration for RAG Chatbot Agent
 */

const fs = require('fs');
const path = require('path');

// Get backend URL from environment or use default
const backendUrl = process.env.REACT_APP_BACKEND_URL || 'https://romaisakhurram-deploy-project.hf.space/';

console.log('🚀 Frontend Setup for RAG Chatbot Agent');
console.log('=' .repeat(50));
console.log(`✅ Backend URL: ${backendUrl}`);

// Create a config file for browser
const clientConfigPath = path.join(__dirname, 'src', 'config.js');
const configContent = `// Auto-generated frontend configuration
// DO NOT EDIT - Generated by setup script

window.__BACKEND_URL__ = '${backendUrl}';
window.__API_BASE__ = '${backendUrl}/api/v1';

console.log('🔗 Backend configured:', window.__BACKEND_URL__);
`;

fs.writeFileSync(clientConfigPath, configContent, 'utf8');
console.log(`✅ Config written to: ${clientConfigPath}`);

console.log('\n📝 Configuration:');
console.log(`   BACKEND_URL: ${backendUrl}`);
console.log(`   API_BASE: ${backendUrl}/api/v1`);

console.log('\n✨ Frontend is ready!');
console.log('   Run: npm start');
